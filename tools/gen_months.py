"""Write crates/cvforge/src/months.rs: abbreviated month names per language, from CLDR via Babel.

cv-builder (wording.py) asks Babel for `get_month_names("abbreviated", context="format",
locale=<primary subtag>)` and keeps English months when Babel does not know the language. This
asks Babel the same for every two- and three-letter code, so cv-forge prints the months
cv-builder prints. Run it with the Babel cv-builder uses (career-ledger's venv), then rebuild:

    ~/Documents/projects/personal/career/career-ledger/.venv/bin/python tools/gen_months.py
"""

from __future__ import annotations

import itertools
import string
from pathlib import Path

import babel
from babel.dates import get_month_names

OUT = Path(__file__).resolve().parent.parent / "crates" / "cvforge" / "src" / "months.rs"


def months(code: str) -> tuple[str, ...] | None:
    try:
        names = get_month_names("abbreviated", context="format", locale=code)
        return tuple(names[i] for i in range(1, 13))
    except Exception:  # noqa: BLE001 - not a language Babel knows: cv-builder keeps English months
        return None


def rust(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    found: dict[str, tuple[str, ...]] = {}
    for n in (2, 3):
        for letters in itertools.product(string.ascii_lowercase, repeat=n):
            code = "".join(letters)
            if code != "en" and (m := months(code)) is not None:
                found[code] = m
    tables: list[tuple[str, ...]] = []
    index: dict[tuple[str, ...], int] = {}
    codes: list[tuple[str, int]] = []
    for code in sorted(found):
        m = found[code]
        if m not in index:
            index[m] = len(tables)
            tables.append(m)
        codes.append((code, index[m]))
    lines = [
        f"//! Abbreviated month names per language, from CLDR (Babel {babel.__version__}), as cv-builder",
        "//! prints them. Generated by `tools/gen_months.py`: do not edit.",
        "",
        f"pub static TABLES: [[&str; 12]; {len(tables)}] = [",
        *(f"    [{', '.join(rust(x) for x in t)}]," for t in tables),
        "];",
        "",
        "/// (language code, index in `TABLES`), sorted by code.",
        f"pub static CODES: [(&str, u16); {len(codes)}] = [",
        *(f"    ({rust(c)}, {i})," for c, i in codes),
        "];",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT}: {len(codes)} languages, {len(tables)} tables")


if __name__ == "__main__":
    main()
